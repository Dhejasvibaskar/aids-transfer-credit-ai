"""
reasoning_generator.py
------------------------
Owner: Person B (AI / Matching Engine)

Purpose:
    Turn matching_engine's raw per-topic results + coverage % + decision
    into a structured, human-readable explanation the HOD can actually
    read — instead of a table of similarity scores.

Design:
    Deterministic fields:
        - overlap_pct
        - missing_units
        - credit_difference

    Gemini is used only for PARTIAL cases where additional academic
    judgment is useful, such as:
        - learning-outcome interpretation
        - bridge-module suggestion
        - human-readable narrative

    ACCEPT and REDO use deterministic rule-based explanations to avoid
    unnecessary Gemini API calls.

Privacy:
    Only topic text, similarity scores, and covered status are sent to
    Gemini. Student-identifying information is never included.

Fallback:
    If Gemini is unavailable, quota-limited, returns invalid JSON, or
    encounters another error, the system falls back to deterministic
    reasoning instead of failing the evaluation.
"""

import os
import json
import time

try:
    from google import genai
except ImportError:
    genai = None


# ---------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------

ALLOWED_MATCH_KEYS = {
    "target_text",
    "best_match_text",
    "similarity",
    "covered",
}

# One bridge module should only be suggested when the gap is small.
MAX_MISSING_TOPICS_FOR_BRIDGE = 2


# ---------------------------------------------------------------------
# Privacy / sanitization
# ---------------------------------------------------------------------

def _sanitize_match_results(match_results: list[dict]) -> list[dict]:
    """
    Strip match results down to the fields that are allowed to be sent
    to Gemini.

    This prevents accidental leakage of student-identifying fields.
    """

    return [
        {
            key: result.get(key)
            for key in ALLOWED_MATCH_KEYS
            if key in result
        }
        for result in match_results
    ]


# ---------------------------------------------------------------------
# Deterministic calculations
# ---------------------------------------------------------------------

def _compute_deterministic_fields(
    match_results: list[dict],
    coverage_pct: float,
    credit_hours_required: float | None,
    credit_hours_completed: float | None,
) -> dict:
    """
    Calculate values that are already known exactly.

    These should never be generated by an LLM.
    """

    missing_units = [
        result["target_text"]
        for result in match_results
        if not result.get("covered")
    ]

    credit_difference = None

    if (
        credit_hours_required is not None
        and credit_hours_completed is not None
    ):
        credit_difference = round(
            credit_hours_required - credit_hours_completed,
            2,
        )

    return {
        "overlap_pct": coverage_pct,
        "missing_units": missing_units,
        "credit_difference": credit_difference,
    }


# ---------------------------------------------------------------------
# Gemini prompt
# ---------------------------------------------------------------------

def _build_prompt(
    sanitized_matches: list[dict],
    coverage_pct: float,
    recommended_status: str,
    missing_units: list[str],
) -> str:
    """
    Build the Gemini prompt.

    Only topic text and similarity information are included.
    """

    matches_block = "\n".join(
        (
            f'- Target: "{match.get("target_text")}" '
            f'| Best match: "{match.get("best_match_text")}" '
            f'| Similarity: {match.get("similarity")} '
            f'| Covered: {match.get("covered")}'
        )
        for match in sanitized_matches
    )

    missing_block = (
        "\n".join(f"- {topic}" for topic in missing_units)
        if missing_units
        else "(none)"
    )

    return f"""
You are assisting an academic transfer-credit evaluation.

Based only on the supplied topic-matching results, produce a structured
academic assessment.

Respond with ONLY a valid JSON object.
Do not use markdown fences.
Do not include any text outside the JSON.

Topic match results:
{matches_block}

Overall coverage: {coverage_pct}%
Recommended status: {recommended_status}

Missing/uncovered target topics:
{missing_block}

Return exactly this JSON structure:

{{
  "learning_outcomes_match": "full" | "partial" | "none",
  "suggested_bridge_module": "<short bridge module title or null>",
  "narrative": "<2-3 sentence plain-language explanation suitable for a department head>"
}}

Rules:

1. Base the assessment only on the supplied topic matches.

2. Never claim a learning outcome is covered unless the topic-matching
   evidence supports it.

3. A bridge module should only be suggested when the gap is narrow
   enough to be reasonably covered by ONE supplementary module.

4. If more than {MAX_MISSING_TOPICS_FOR_BRIDGE} topics are missing,
   suggested_bridge_module must be null.

5. If the gap is too broad for one bridge module, clearly state this in
   the narrative.

6. If coverage is very low or no meaningful topics matched, do not
   exaggerate the level of learning-outcome equivalence.

7. Do not introduce student names, IDs, grades, institutions, or any
   information not included in the topic-matching evidence.
""".strip()


# ---------------------------------------------------------------------
# Gemini API call
# ---------------------------------------------------------------------

def _call_gemini(
    prompt: str,
    model: str | None = None,
) -> str | None:
    """
    Call Gemini with limited retry handling.

    Transient connection failures are retried.

    Errors such as:
        - quota exhausted (429)
        - model unavailable (404)

    are not retried because retrying immediately would only waste time
    and additional requests.
    """

    api_key = os.environ.get("GEMINI_API_KEY")

    if genai is None:
        print(
            "[reasoning_generator] "
            "google-genai package unavailable; using fallback."
        )
        return None

    if not api_key:
        print(
            "[reasoning_generator] "
            "GEMINI_API_KEY not set; using fallback."
        )
        return None

    if model is None:
        model = os.environ.get(
            "GEMINI_REASONING_MODEL",
            "gemini-3.6-flash",
        )

    client = genai.Client(api_key=api_key)

    max_attempts = 3

    for attempt in range(1, max_attempts + 1):

        try:
            response = client.models.generate_content(
                model=model,
                contents=prompt,
            )

            text = response.text

            if text:
                return text

            print(
                "[reasoning_generator] "
                "Gemini returned an empty response."
            )

            return None

        except Exception as exc:
            error_text = str(exc)

            # ---------------------------------------------
            # Quota exhausted: do NOT retry
            # ---------------------------------------------
            if (
                "429" in error_text
                or "RESOURCE_EXHAUSTED" in error_text
                or "quota" in error_text.lower()
            ):
                print(
                    "[reasoning_generator] "
                    "Gemini quota exhausted; "
                    "using fallback without retry."
                )
                return None

            # ---------------------------------------------
            # Invalid / retired model: do NOT retry
            # ---------------------------------------------
            if (
                "404" in error_text
                or "NOT_FOUND" in error_text
            ):
                print(
                    "[reasoning_generator] "
                    "Gemini model unavailable; "
                    "using fallback without retry."
                )
                return None

            # ---------------------------------------------
            # Other errors may be temporary
            # ---------------------------------------------
            print(
                "[reasoning_generator] "
                f"Gemini attempt "
                f"{attempt}/{max_attempts} failed: "
                f"{exc}"
            )

            if attempt < max_attempts:
                wait_seconds = 2 * attempt

                print(
                    "[reasoning_generator] "
                    f"Retrying in {wait_seconds} seconds..."
                )

                time.sleep(wait_seconds)

    print(
        "[reasoning_generator] "
        "Gemini unavailable after retries; using fallback."
    )

    return None


# ---------------------------------------------------------------------
# Gemini response parser
# ---------------------------------------------------------------------

def _parse_gemini_json(text: str) -> dict:
    """
    Parse Gemini JSON.

    Markdown fences are stripped defensively in case Gemini returns them.
    """

    cleaned = text.strip()

    if cleaned.startswith("```"):
        cleaned = cleaned.strip("`").strip()

        if cleaned.lower().startswith("json"):
            cleaned = cleaned[4:].strip()

    parsed = json.loads(cleaned)

    if not isinstance(parsed, dict):
        raise ValueError(
            "Gemini response must be a JSON object."
        )

    return parsed


# ---------------------------------------------------------------------
# Deterministic fallback
# ---------------------------------------------------------------------

def _fallback_reasoning(
    coverage_pct: float,
    recommended_status: str,
    missing_units: list[str],
) -> dict:
    """
    Generate deterministic reasoning when Gemini is not used or cannot
    provide a valid response.
    """

    status_to_outcome = {
        "accept": "full",
        "partial": "partial",
        "redo": "none",
    }

    learning_outcomes_match = status_to_outcome.get(
        recommended_status,
        "none",
    )

    bridge = None
    gap_too_broad_for_bridge = False

    if recommended_status == "partial" and missing_units:

        if len(missing_units) <= MAX_MISSING_TOPICS_FOR_BRIDGE:

            bridge = (
                "Bridge module covering: "
                + ", ".join(missing_units)
            )

        else:
            gap_too_broad_for_bridge = True

    # -------------------------------------------------------------
    # ACCEPT
    # -------------------------------------------------------------

    if recommended_status == "accept":

        if missing_units:
            narrative = (
                f"Coverage is {coverage_pct}%, meeting the required "
                "threshold for transfer-credit acceptance. "
                f"{len(missing_units)} target topic(s) were not fully "
                "covered, but overall syllabus overlap is sufficient "
                "for the recommended acceptance."
            )
        else:
            narrative = (
                f"Coverage is {coverage_pct}%, meeting the required "
                "threshold for transfer-credit acceptance. "
                "All evaluated target topics were sufficiently covered."
            )

    # -------------------------------------------------------------
    # PARTIAL
    # -------------------------------------------------------------

    elif recommended_status == "partial":

        narrative = (
            f"Coverage is {coverage_pct}%, resulting in a partial "
            "equivalence recommendation. "
        )

        if missing_units:
            narrative += (
                f"{len(missing_units)} target topic(s) were not "
                "sufficiently covered."
            )

            if gap_too_broad_for_bridge:
                narrative += (
                    " The gap spans too many topics for a single "
                    "bridge module, so broader supplementary study "
                    "would be required."
                )

        else:
            narrative += (
                "The available evidence indicates partial rather "
                "than complete equivalence."
            )

    # -------------------------------------------------------------
    # REDO
    # -------------------------------------------------------------

    elif recommended_status == "redo":

        narrative = (
            f"Coverage is {coverage_pct}%, which is below the required "
            "level for transfer-credit equivalence. "
        )

        if missing_units:
            narrative += (
                f"{len(missing_units)} target topic(s) were not "
                "sufficiently covered, so the course is recommended "
                "for redo."
            )
        else:
            narrative += (
                "The overall level of demonstrated syllabus overlap "
                "is insufficient, so the course is recommended "
                "for redo."
            )

    # -------------------------------------------------------------
    # Unknown status
    # -------------------------------------------------------------

    else:
        narrative = (
            f"Coverage is {coverage_pct}%. "
            f"The recommendation status is "
            f"'{recommended_status}'."
        )

    return {
        "learning_outcomes_match": learning_outcomes_match,
        "suggested_bridge_module": bridge,
        "narrative": narrative,
    }


# ---------------------------------------------------------------------
# Public interface
# ---------------------------------------------------------------------

def generate(
    match_results: list[dict],
    coverage_pct: float,
    recommended_status: str,
    credit_hours_required: float | None = None,
    credit_hours_completed: float | None = None,
) -> dict:
    """
    Generate structured reasoning for one evaluated target course.

    Gemini is called only for PARTIAL cases.

    ACCEPT and REDO use deterministic explanations.

    Returns:
        {
            "overlap_pct": float,
            "learning_outcomes_match": "full" | "partial" | "none",
            "missing_units": list[str],
            "credit_difference": float | None,
            "suggested_bridge_module": str | None,
            "narrative": str
        }
    """

    recommended_status = (
        recommended_status or ""
    ).strip().lower()

    # -------------------------------------------------------------
    # Values calculated locally
    # -------------------------------------------------------------

    deterministic = _compute_deterministic_fields(
        match_results=match_results,
        coverage_pct=coverage_pct,
        credit_hours_required=credit_hours_required,
        credit_hours_completed=credit_hours_completed,
    )

    ai_fields = None

    # -------------------------------------------------------------
    # Gemini only for PARTIAL
    # -------------------------------------------------------------

    if recommended_status == "partial":

        sanitized = _sanitize_match_results(
            match_results
        )

        prompt = _build_prompt(
            sanitized_matches=sanitized,
            coverage_pct=coverage_pct,
            recommended_status=recommended_status,
            missing_units=deterministic[
                "missing_units"
            ],
        )

        raw_response = _call_gemini(prompt)

        if raw_response is not None:

            try:
                ai_fields = _parse_gemini_json(
                    raw_response
                )

            except (
                json.JSONDecodeError,
                ValueError,
            ) as exc:

                print(
                    "[reasoning_generator] "
                    "Failed to parse Gemini response; "
                    f"using fallback: {exc}"
                )

                ai_fields = None

    # -------------------------------------------------------------
    # ACCEPT, REDO, or failed Gemini → deterministic fallback
    # -------------------------------------------------------------

    if ai_fields is None:

        ai_fields = _fallback_reasoning(
            coverage_pct=coverage_pct,
            recommended_status=recommended_status,
            missing_units=deterministic[
                "missing_units"
            ],
        )

    # -------------------------------------------------------------
    # Final output
    # -------------------------------------------------------------

    return {
        "overlap_pct": deterministic[
            "overlap_pct"
        ],
        "learning_outcomes_match": ai_fields.get(
            "learning_outcomes_match",
            "none",
        ),
        "missing_units": deterministic[
            "missing_units"
        ],
        "credit_difference": deterministic[
            "credit_difference"
        ],
        "suggested_bridge_module": ai_fields.get(
            "suggested_bridge_module"
        ),
        "narrative": ai_fields.get(
            "narrative",
            "",
        ),
    }


